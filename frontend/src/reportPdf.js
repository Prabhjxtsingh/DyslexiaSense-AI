const margin = 18;
const pageBottom = 280;

export async function createAssessmentPdf(result) {
  const { jsPDF } = await import("jspdf");
  const pdf = new jsPDF({ format: "a4", unit: "mm" });
  const contentWidth = pdf.internal.pageSize.getWidth() - margin * 2;
  let cursorY = 20;

  const addWrappedText = (text, { size = 10, bold = false, gap = 2 } = {}) => {
    pdf.setFont("helvetica", bold ? "bold" : "normal");
    pdf.setFontSize(size);
    const lines = pdf.splitTextToSize(String(text), contentWidth);
    for (const line of lines) {
      if (cursorY > pageBottom) {
        pdf.addPage();
        cursorY = 20;
      }
      pdf.text(line, margin, cursorY);
      cursorY += size * 0.42;
    }
    cursorY += gap;
  };

  const addSection = (title, details) => {
    addWrappedText(title, { size: 14, bold: true, gap: 1 });
    for (const detail of details) {
      addWrappedText(detail, { gap: 1 });
    }
    cursorY += 3;
  };

  addWrappedText("DyslexiaSense AI - Activity Results", {
    size: 20,
    bold: true,
    gap: 3,
  });
  addWrappedText(
    `Completed: ${new Date(result.completedAt).toLocaleString()}`,
    { size: 10 },
  );
  if (result.participantLabel) {
    addWrappedText(`Participant label: ${result.participantLabel}`, { size: 10 });
  }

  addSection("Reading fluency", [
    `${result.reading.correctWords} of ${result.reading.totalWords} words recorded correctly`,
    `Observed accuracy: ${Math.round(result.reading.accuracy * 100)}%`,
    `Correct words per minute: ${result.reading.wordsPerMinute.toFixed(1)}`,
    `Elapsed time: ${result.reading.elapsedSeconds} seconds`,
    `Omissions: ${result.reading.omissions}; substitutions: ${result.reading.substitutions}`,
  ]);

  for (const [title, key] of [
    ["Sound blending", "phonology"],
    ["Visual recognition", "visual"],
    ["Spelling", "spelling"],
  ]) {
    const activity = result[key];
    addSection(title, [
      `${activity.correctCount} of ${activity.totalCount} correct (${Math.round(activity.accuracy * 100)}% observed accuracy)`,
      activity.averageResponseTimeMs === null
        ? "Average response time: no answered items"
        : `Average response time: ${activity.averageResponseTimeMs.toFixed(0)} ms`,
      ...activity.items.flatMap((item, index) => [
        `${index + 1}. ${item.prompt}`,
        `   Response: ${item.response || "Skipped"}; ${item.correct ? "correct" : `expected ${item.answer}`}${
          item.responseTimeMs === null ? "" : `; ${item.responseTimeMs.toFixed(0)} ms`
        }`,
      ]),
    ]);
  }

  if (result.researchModel) {
    addSection("Separate Dyt research model score", [
      `Dyt dyslexia label "${result.researchModel.positive_label}": ${Math.round(result.researchModel.score * 100)}%; "${result.researchModel.negative_label}": ${100 - Math.round(result.researchModel.score * 100)}%`,
      `Model: ${result.researchModel.model}; predicted label: ${result.researchModel.prediction}`,
      `Generated: ${new Date(result.researchModel.generatedAt).toLocaleString()}`,
      "This uncalibrated model score uses a separate 197-field Dyt input form. It is not calculated from the activities and is not a probability of diagnosis.",
    ]);
  } else {
    addSection("Chance of dyslexia diagnosis", [
      "Not estimated. The activity results do not provide a probability of diagnosis.",
    ]);
  }

  addWrappedText(
    "Important: These educational activity observations and any separate research-model score are not a diagnosis. The Dyt model score is not a person's chance of receiving a diagnosis. Consult a qualified professional for assessment.",
    { size: 10, bold: true, gap: 2 },
  );
  addWrappedText(
    "This report was generated by DyslexiaSense AI and contains results from this browser session.",
    { size: 9, gap: 0 },
  );

  const pageCount = pdf.getNumberOfPages();
  for (let page = 1; page <= pageCount; page += 1) {
    pdf.setPage(page);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(8);
    pdf.text(
      `Page ${page} of ${pageCount}`,
      pdf.internal.pageSize.getWidth() - margin,
      288,
      { align: "right" },
    );
  }

  return pdf;
}

export async function downloadAssessmentPdf(result) {
  const safeId = String(result.id).replace(/[^a-zA-Z0-9_-]/g, "");
  const pdf = await createAssessmentPdf(result);
  const url = URL.createObjectURL(pdf.output("blob"));
  const link = document.createElement("a");
  link.href = url;
  link.download = `dyslexiasense-${safeId || "results"}.pdf`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 10_000);
}
